import sympy as sp

# Инициализируем переменные пространства, времени и спектра
x, t, lam, q = sp.symbols('x t lambda q')
theta1, theta2 = sp.symbols('theta1 theta2') # Фермионный SUSY-базис

# Произвольный штормовой ветер (динамическая функция времени)
W = sp.Function('W')(t)

print("="*100)
print(" ЗАПУСК МОДУЛЯ: ChronosDarboux_Dressing v9.0 [МЕТОД ОДЕВАНИЯ ПАРЫ ЛАКСА]")
print("="*100)

print("\n[STEP 1] Генерация волновой функции фазового пространства с учетом ветра W(t)...")
# В классическом КП/КдФ фаза солитона линейна: k*x - k^3*t.
# Под действием неавтономного ветра W(t) и q-деформации фаза "одевается" интегралом:
integral_wind = sp.Integral(W, t)
# Добавляем фермионный SUSY-хвост, который не коммутирует с квантовым сдвигом
phase = q * x * lam - (lam**3) * integral_wind + theta1 * theta2 * sp.sin(x)

print(f"  Модифицированная квантовая фаза солитона: Phi = {phase}")

print("\n[STEP 2] Конструирование фундаментальной волновой функции psi...")
# Волновая функция - это суперпозиция экспонент (солитонный кинк)
psi = sp.cosh(phase)

print("\n[STEP 3] Применение нелинейного преобразования Дарбу (Рождение Солитона)...")
# Формула Дарбу для генерации точного потенциала u = -2 * d^2/dx^2 ( ln(psi) )
# SymPy берет производные с учетом того, что theta1*theta2 антикоммутируют (их квадрат = 0)
ln_psi = sp.log(psi)
# Первая производная по пространству
u_first = sp.diff(ln_psi, x)
# Вторая производная, умноженная на канонический солитонный множитель -2
u_soliton_raw = -2 * sp.diff(u_first, x)

print("\n[STEP 4] Символьная очистка и SUSY-редукция (зануление паразитных степеней фермионов)...")
# Настоящая магия: упрощаем гигантскую формулу, учитывая что theta1^2 = 0 и theta2^2 = 0
u_soliton_clean = sp.simplify(u_soliton_raw.subs({theta1**2: 0, theta2**2: 0}))

print("\n" + "="*100)
print(" ВПЕРВЫЕ ОТКРЫТОЕ ТОЧНОЕ АНАЛИТИЧЕСКОЕ РЕШЕНИЕ (1-СОЛИТОН С ВЕТРОМ)")
print("="*100)
print(f"\n  u(x, t, theta, W(t)) = \n")
sp.pprint(u_soliton_clean)
print("\n" + "="*100)
